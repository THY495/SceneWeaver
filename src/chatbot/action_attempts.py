"""Fenced, bounded action attempts; technical pauses are never character decisions."""

import hashlib
import json
from datetime import timedelta

from sqlalchemy import select

from .agreements import authorize
from .storage import ActionAttempt, Conversation, Story, Task, now


def digest(command):
    return hashlib.sha256(json.dumps(command, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def reserve(db, task, actor_id, step, command):
    from .providers import ProviderError
    from .runtime import StaleTask

    ref = command.get("agreement")
    if not ref:
        return None
    key = f"task:{task.id}:{step}"
    with db.session.begin() as s:
        actor = s.get(Conversation, actor_id)
        story = s.scalar(select(Story).where(Story.id == actor.story_id).with_for_update())
        current = s.get(Task, task.id)
        scene_task = current.kind in {"scene_run", "npc_step"}
        parent = s.get(Conversation, current.session_id) if current.session_id else None
        if (
            actor.story_id != (current.payload["story_id"] if scene_task else parent.story_id)
            or actor.owner_id != current.owner_id
            or actor.id not in current.payload.get("audience", [])
            or actor.current_state.get("player")
        ):
            raise StaleTask("执行者不属于当前NPC任务")
        if (
            current.status != "running"
            or current.lease_version != task.lease_version
            or not current.lease_until
            or current.lease_until <= now()
            or (parent is not None and parent.epoch != task.epoch)
        ):
            raise StaleTask("执行尝试所属任务已过期")
        if story.settings.get("paused") and current.kind != "npc_step":
            raise StaleTask("剧情已暂停")
        if scene_task:
            from .scene_tasks import valid_scene

            if not valid_scene(s, current, story):
                raise StaleTask("场景活动已停止")
        old = s.get(ActionAttempt, key)
        if old and old.command_hash != digest(command):
            raise StaleTask("同一执行尝试不能更改动作")
        if old and old.status in {"completed", "failed"}:
            return key
        authorize(s, actor, command)
        others = list(
            s.scalars(
                select(ActionAttempt).where(
                    ActionAttempt.story_id == story.id,
                    ActionAttempt.item_id == ref["item_id"],
                    ActionAttempt.proposal_version == ref["version"],
                    ActionAttempt.status.in_(["reserved", "paused", "failed"]),
                )
            )
        )
        for other in others:
            owner = s.get(Task, other.task_id)
            if (
                other.id != key
                and other.status == "reserved"
                and owner.status == "running"
                and owner.lease_version == other.task_lease_version
                and (owner.lease_until and owner.lease_until > now())
            ):
                raise ProviderError("该事项已有有效执行尝试")
            if other.retry_at and other.retry_at > now():
                raise ProviderError("执行尝试正在退避，等待新的行动机会")
            if other.id != key and other.status == "reserved":
                other.status, other.pause_reason = "paused", "lease_expired"
        if old:
            old.task_lease_version, old.status, old.pause_reason = task.lease_version, "reserved", None
            old.retry_at = None
        else:
            s.add(
                ActionAttempt(
                    id=key,
                    story_id=story.id,
                    actor_id=actor_id,
                    task_id=task.id,
                    task_lease_version=task.lease_version,
                    proposal_id=ref["proposal_id"],
                    proposal_version=ref["version"],
                    item_id=ref["item_id"],
                    command_hash=digest(command),
                )
            )
    return key


def check_attempt(s, task, actor, step, command):
    from .runtime import StaleTask

    if not command.get("agreement"):
        return None
    row = s.get(ActionAttempt, f"task:{task.id}:{step}")
    if (
        not row
        or row.actor_id != actor.id
        or row.task_lease_version != task.lease_version
        or (row.status != "reserved" or row.command_hash != digest(command))
    ):
        raise StaleTask("执行尝试未持有当前租约")
    return row


def pause_task(db, task, reason):
    """No event, observation, dialogue or agreement decision is generated by an outage."""
    with db.session() as s:
        story_ids = list(
            s.scalars(
                select(ActionAttempt.story_id)
                .where(ActionAttempt.task_id == task.id, ActionAttempt.status == "reserved")
                .distinct()
            )
        )
    for sid in story_ids:
        with db.session.begin() as s:
            s.scalar(select(Story).where(Story.id == sid).with_for_update())
            for attempt in s.scalars(
                select(ActionAttempt).where(
                    ActionAttempt.task_id == task.id,
                    ActionAttempt.task_lease_version == task.lease_version,
                    ActionAttempt.status == "reserved",
                )
            ):
                attempt.status, attempt.pause_reason = "paused", reason
                attempt.retry_at = now() + timedelta(seconds=min(60, 5 * 2 ** min(task.attempt, 3)))
